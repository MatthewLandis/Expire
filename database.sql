-- Expire database setup (PostgreSQL)
-- Run this once in pgAdmin's Query Tool on an empty database.
-- The project has no EF migrations, so this file is how the tables get made.

-- ---------- Login tables (ASP.NET Core Identity) ----------
-- These are the standard tables Identity expects. Only AspNetUsers is
-- really used, but Identity needs the others to exist.

CREATE TABLE "AspNetRoles" (
    "Id" text NOT NULL PRIMARY KEY,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text
);

CREATE TABLE "AspNetUsers" (
    "Id" text NOT NULL PRIMARY KEY,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL
);

CREATE TABLE "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

CREATE TABLE "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

CREATE TABLE "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("LoginProvider", "ProviderKey")
);

CREATE TABLE "AspNetUserRoles" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("UserId", "RoleId")
);

CREATE TABLE "AspNetUserTokens" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    PRIMARY KEY ("UserId", "LoginProvider", "Name")
);

-- No two users can have the same username, and lookups by email stay fast
CREATE UNIQUE INDEX "UserNameIndex" ON "AspNetUsers" ("NormalizedUserName");
CREATE INDEX "EmailIndex" ON "AspNetUsers" ("NormalizedEmail");
CREATE UNIQUE INDEX "RoleNameIndex" ON "AspNetRoles" ("NormalizedName");

-- ---------- Expire's own tables ----------

-- Every food in someone's fridge (see Models/FoodItem.cs)
CREATE TABLE "FoodItems" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" text NOT NULL,
    "Name" text NOT NULL,
    "Quantity" integer NOT NULL DEFAULT 1,
    "ExpiryDate" date,                            -- optional
    "Status" text NOT NULL DEFAULT 'Available',   -- Available, Eaten or Wasted ("Thrown out")
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "Notes" text,                                 -- optional
    "Slot" integer NOT NULL DEFAULT 0             -- 0-14 = freezer, 15-44 = fridge
);

-- A display name and bio for the profile page (see Models/UserProfile.cs).
-- UserId is the same Id as the user's row in AspNetUsers.
CREATE TABLE "UserProfiles" (
    "UserId" text NOT NULL PRIMARY KEY,
    "DisplayName" text,
    "Bio" text
);
